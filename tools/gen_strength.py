#!/usr/bin/env python3
"""Strength data for every element: how much stress it takes before it gives, and whether it is brittle.

Hardness and elastic moduli come from pymatgen's element table (dev_scripts/periodic_table_resources/
elemental_properties.yaml, from Wikipedia's data pages on the elements).

- Strength: Tabor's relation, hardness = 3 x flow stress, using Vickers hardness where there is one and
  Brinell otherwise. Tabor's flow stress is that of the worked metal: above a fully softened (annealed)
  handbook yield strength, below a hard-drawn one.
- Brittle or not: Pugh's ratio, bulk modulus / shear modulus, below 1.75 brittle; a few well-known
  exceptions are set by hand (listed in the report). Non-metals are brittle.
- Elements with no hardness: estimated from the melting point, which tracks bond strength, fitted to the
  metals that have data.

    node tools/dump_chem.mjs > tools/chem_materials.json
    python3 tools/gen_strength.py <pymatgen>/dev_scripts/periodic_table_resources/elemental_properties.yaml
"""
import json, math, os, sys
import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1] if len(sys.argv) > 1 else '/tmp/pmg-src/p/dev_scripts/periodic_table_resources/elemental_properties.yaml'
d = yaml.safe_load(open(SRC))
data = lambda k: d[k]['data']
HV, HB, B, G = data('Vickers hardness'), data('Brinell hardness'), data('Bulk modulus'), data('Rigidity modulus')

elements = [m for m in json.load(open(os.path.join(HERE, 'chem_materials.json'))) if m.get('element')]

# Where Brinell and Vickers both exist and disagree by more than this factor, the Brinell figure is taken to
# be wrong (gold's is listed at 2450 MPa against 216 Vickers: a slip of a factor of ten)
DISAGREE = 2.5
# Brittle at room temperature although Pugh's ratio says otherwise, or the other way round
BRITTLE_ANYWAY = {'Bi': "bismuth cleaves like a crystal", 'W': "tungsten is brittle below a few hundred °C",
                  'Mn': "manganese is hard and brittle", 'Be': "beryllium is brittle", 'Ir': "iridium cracks when worked cold"}
DUCTILE_ANYWAY = {'U': "uranium is malleable (the moduli listed for it look wrong)"}
# Set by hand: the game's carbon is coal and graphite, far weaker than its melting point suggests (flow stress, MPa)
BY_HAND = {'C': (30, "graphite: weak and brittle, whatever its melting point")}
PUGH = 1.75

rows, notes = {}, []
for m in elements:
    el = m['key']
    hv, hb = HV.get(el), HB.get(el)
    if hv and hb and max(hv, hb) / min(hv, hb) > DISAGREE:
        notes.append('%s: Brinell %g MPa disagrees with Vickers %g MPa; Vickers used' % (m['name'], hb, hv))
    if hv:
        hard, src = hv, 'Vickers'
    elif hb:
        hard, src = hb * 1.05, 'Brinell'                 # Brinell reads a little below Vickers on soft metals
    else:
        hard, src = None, None
    pugh = B[el] / G[el] if B.get(el) and G.get(el) else None
    if not m.get('metal'):
        brittle, why = True, 'not a metal'
    elif el in BRITTLE_ANYWAY:
        brittle, why = True, BRITTLE_ANYWAY[el]
    elif el in DUCTILE_ANYWAY:
        brittle, why = False, DUCTILE_ANYWAY[el]
    elif pugh is not None:
        brittle, why = pugh < PUGH, 'Pugh ratio %.2f' % pugh
    else:
        brittle, why = False, 'metal, no moduli: taken as ductile'
    if el in BY_HAND:
        hard, src, why = BY_HAND[el][0] * 3, 'by hand', BY_HAND[el][1]
    rows[el] = {'m': m, 'hard': hard, 'src': src, 'pugh': pugh, 'brittle': brittle, 'why': why}

# fit log hardness against log melting point on the metals with data, to estimate the rest
pts = [(math.log10(r['m']['melt'] + 273.15), math.log10(r['hard'])) for r in rows.values()
       if r['hard'] and r['m'].get('metal') and r['m']['melt'] is not None and r['m']['melt'] > -40]
n = len(pts); mx = sum(p[0] for p in pts) / n; my = sum(p[1] for p in pts) / n
slope = sum((p[0] - mx) * (p[1] - my) for p in pts) / sum((p[0] - mx) ** 2 for p in pts)
icpt = my - slope * mx
resid = sorted(abs(p[1] - (icpt + slope * p[0])) for p in pts)
typical_factor = 10 ** resid[len(resid) // 2]
for r in rows.values():
    if r['hard'] is None:
        melt = r['m']['melt']
        if melt is None or melt < 25:                # liquids and gases at room temperature have no strength
            r['hard'], r['src'] = 0, 'none (not solid)'
        else:
            r['hard'], r['src'] = 10 ** (icpt + slope * math.log10(melt + 273.15)), 'estimate'

SRCCODE = {'Vickers': 0, 'Brinell': 1, 'estimate': 2, 'none (not solid)': 3, 'by hand': 4}
out = ['// Generated by tools/gen_strength.py from pymatgen\'s element data (hardness, elastic moduli). Do not edit.',
       '// For each element: [flow stress in MPa (Tabor: hardness / 3), brittle (1) or not, source].',
       '// source: 0 Vickers hardness, 1 Brinell hardness, 2 estimated from the melting point, 3 not a solid, 4 by hand.',
       'export const STRENGTH = {']
for el, r in rows.items():
    out.append('  %s: [%s, %d, %d],' % (json.dumps(el), ('%.3g' % (r['hard'] / 3)), r['brittle'], SRCCODE[r['src']]))
out.append('};')
open(os.path.join(HERE, '..', 'src', 'sim', 'strength.gen.js'), 'w').write('\n'.join(out) + '\n')

# ---------- report ----------
rep = ['# Strength data report', '', 'Generated by `tools/gen_strength.py` from pymatgen\'s element data.', '',
       '## Where the numbers come from', '']
cnt = {}
for r in rows.values():
    cnt[r['src']] = cnt.get(r['src'], 0) + 1
rep += ['| source | elements |', '|---|---|'] + ['| %s | %d |' % (k, v) for k, v in sorted(cnt.items(), key=lambda x: -x[1])]
rep += ['', 'Estimates from the melting point: log10(hardness) = %.2f + %.2f log10(Tm), fitted on %d metals; typically'
        ' within a factor of %.1f.' % (icpt, slope, n, typical_factor), '',
        '## Data that looked wrong', ''] + ['- ' + x for x in notes] + ['',
        '## Set by hand', ''] + ['- %s brittle: %s' % (k, v) for k, v in BRITTLE_ANYWAY.items()] + ['- %s ductile: %s' % (k, v) for k, v in DUCTILE_ANYWAY.items()] + ['- %s %g MPa: %s' % (k, v[0], v[1]) for k, v in BY_HAND.items()] + ['']
rep += ['## Common metals', '',
        'Flow stress is Tabor\'s, for a worked metal; annealed handbook yield strengths are lower, hard-drawn ones higher.', '',
        '| metal | flow stress | brittle | why | from |', '|---|---|---|---|---|']
for el in ['Fe', 'Cu', 'Al', 'Ti', 'Ni', 'Cr', 'W', 'Pb', 'Sn', 'Zn', 'Mg', 'Au', 'Ag', 'Pt', 'U', 'Bi', 'Na', 'Hg', 'C', 'S', 'Si']:
    r = rows[el]
    rep.append('| %s | %.3g MPa | %s | %s | %s |' % (r['m']['name'], r['hard'] / 3, 'yes' if r['brittle'] else 'no', r['why'], r['src']))
open(os.path.join(HERE, 'strength-report.md'), 'w').write('\n'.join(rep) + '\n')
print('\n'.join(rep))
